/* Wzór znaku 5x7 (5 kolumn, bit 0 = górny wiersz) - także dla tekstu rysowanego w paskach (gfx.c) */
const uint8_t *lcd_glyph(char ch)
{
    if (ch < 0x20 || ch > 0x7E) ch = '?';
    return font5x7[ch - 0x20];
}

/* Jeden znak: bufor komórki 6x8 * scale, wysłany jednym oknem */
static void lcd_char(uint16_t x, uint16_t y, char ch, uint16_t fg, uint16_t bg, uint8_t s)
{
    static uint8_t buf[6 * 8 * 4 * 4 * 2];       /* do scale = 4 */
    if (s < 1) s = 1;
    if (s > 4) s = 4;
    if (ch < 0x20 || ch > 0x7E) ch = '?';
    const uint8_t *g = font5x7[ch - 0x20];
    uint16_t w = 6 * s, h = 8 * s;
    if (x + w > LCD_W || y + h > LCD_H) return;

    uint32_t k = 0;
    for (uint16_t py = 0; py < h; py++) {
        uint8_t row = py / s;
        for (uint16_t px = 0; px < w; px++) {
            uint8_t col = px / s;
            uint8_t on = (col < 5) && (row < 7) && (g[col] >> row & 1);
            uint16_t c = on ? fg : bg;
            buf[k++] = c >> 8;
            buf[k++] = c & 0xFF;
        }
    }
    lcd_set_window(x, y, x + w - 1, y + h - 1);
    uint8_t cmd = 0x2C;
    CS_LO();
    DC_CMD();
    spi_tx(&cmd, 1);
    DC_DAT();
    spi_tx(buf, (uint16_t)k);
    CS_HI();
}

/* Zapis ciągły do okna: CS zostaje niski, DC = dane, piksele wysyła DMA (gfx.c) */
void lcd_begin_write(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1)
{
    lcd_set_window(x0, y0, x1, y1);
    uint8_t cmd = 0x2C;
    CS_LO();
    DC_CMD();
    spi_tx(&cmd, 1);
    DC_DAT();
}

void lcd_end_write(void)
{
    CS_HI();
}

void lcd_text(uint16_t x, uint16_t y, const char *s, uint16_t fg, uint16_t bg, uint8_t scale)
{
    while (*s) {
        lcd_char(x, y, *s++, fg, bg, scale);
        x += 6 * scale;
    }
}
